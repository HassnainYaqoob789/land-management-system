// Official, branded PDF tables (pdfkit, standard PDF fonts — no font files).
//
// Every page carries the Mari Energies logo, the organisation and report
// title, and a footer with the confidentiality marking, the generation stamp
// and "Page n of N". Table headers repeat on every page; columns are sized to
// the page and long text wraps instead of being clipped; numbers are
// right-aligned. Subtotal and total rows are drawn bold with a rule above.
import PDFDocument from 'pdfkit';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export interface PdfColumn { header: string; align?: 'left' | 'right'; weight?: number }
export interface PdfTable {
  title: string;
  subtitle?: string;
  /** Label/value pairs printed under the title: reference, period, scope, unit, filters, generated by. */
  meta: [string, string][];
  columns: PdfColumn[];
  rows: string[][];
  emphasis?: Set<number>;
  /** Notes printed after the table (flags, limitations, definitions). */
  notes?: string[];
  classification?: string;
  organisation?: string;
  department?: string;
}

let logo: Buffer | null | undefined;
function logoBytes(): Buffer | null {
  if (logo !== undefined) return logo;
  try { logo = readFileSync(join(process.cwd(), 'public', 'images', 'mari-energies-logo.png')); } catch { logo = null; }
  return logo;
}

export function renderPdf(t: PdfTable): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margins: { top: 36, bottom: 48, left: 32, right: 32 }, bufferPages: true,
      info: { Title: t.title, Author: t.organisation ?? 'Mari Energies Limited', Creator: 'Mari Energies LMS' } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const W = doc.page.width - doc.page.margins.left - doc.page.margins.right;
    const L = doc.page.margins.left;
    const bottom = () => doc.page.height - doc.page.margins.bottom;
    const weights = t.columns.map((c) => c.weight ?? 1);
    const sum = weights.reduce((a, b) => a + b, 0) || 1;
    const widths = weights.map((w) => (w / sum) * W);
    const pad = 3;

    const masthead = (first: boolean) => {
      const img = logoBytes();
      const top = doc.page.margins.top;
      if (img) doc.image(img, L, top - 6, { fit: [first ? 46 : 30, first ? 46 : 30] });
      const x = L + (first ? 56 : 40);
      doc.fillColor('#0b3b6e').font('Helvetica-Bold').fontSize(first ? 13 : 10)
        .text(t.organisation ?? 'Mari Energies Limited', x, top - 2, { width: W - (x - L) });
      doc.fillColor('#333').font('Helvetica').fontSize(8)
        .text(`${t.department ?? 'Land Management'} · Land Management System`, x, doc.y, { width: W - (x - L) });
      doc.fillColor('#111').font('Helvetica-Bold').fontSize(first ? 12 : 9).text(t.title, x, doc.y + 2, { width: W - (x - L) });
      doc.y = Math.max(doc.y, top + (first ? 44 : 30)) + 4;
      doc.moveTo(L, doc.y).lineTo(L + W, doc.y).lineWidth(0.6).strokeColor('#9aa8ba').stroke();
      doc.y += 6;
    };

    const header = () => {
      const y = doc.y;
      doc.font('Helvetica-Bold').fontSize(7.5);
      const h = Math.max(...t.columns.map((c, i) => doc.heightOfString(c.header, { width: widths[i] - 2 * pad }))) + 2 * pad;
      doc.rect(L, y, W, h).fill('#e8eef6');
      let x = L;
      t.columns.forEach((c, i) => {
        doc.fillColor('#111').text(c.header, x + pad, y + pad, { width: widths[i] - 2 * pad, align: c.align ?? 'left' });
        x += widths[i];
      });
      doc.y = y + h;
    };

    masthead(true);
    if (t.subtitle) doc.fillColor('#333').font('Helvetica').fontSize(8.5).text(t.subtitle, L, doc.y, { width: W });
    doc.font('Helvetica').fontSize(8);
    for (const [k, v] of t.meta) {
      doc.fillColor('#555').font('Helvetica-Bold').text(`${k}: `, L, doc.y, { continued: true, width: W })
        .fillColor('#111').font('Helvetica').text(v || '—');
    }
    doc.y += 6;
    header();

    t.rows.forEach((cells, k) => {
      const bold = !!t.emphasis?.has(k);
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(7.5);
      const h = Math.max(10, ...t.columns.map((_, i) => doc.heightOfString(cells[i] ?? '', { width: widths[i] - 2 * pad }))) + 2 * pad;
      if (doc.y + h > bottom()) { doc.addPage(); masthead(false); header(); doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(7.5); }
      const y = doc.y;
      if (bold) doc.moveTo(L, y).lineTo(L + W, y).lineWidth(0.6).strokeColor('#555').stroke();
      else if (k % 2 === 1) doc.rect(L, y, W, h).fill('#f6f8fb');
      let x = L;
      t.columns.forEach((c, i) => {
        doc.fillColor('#111').text(cells[i] ?? '', x + pad, y + pad, { width: widths[i] - 2 * pad, align: c.align ?? 'left' });
        x += widths[i];
      });
      doc.y = y + h;
    });
    if (!t.rows.length) doc.font('Helvetica-Oblique').fontSize(8.5).fillColor('#555').text('No records match this report.', L, doc.y + 6);

    if (t.notes?.length) {
      doc.y += 8;
      doc.font('Helvetica').fontSize(7.5).fillColor('#333');
      for (const n of t.notes) {
        if (doc.y + 12 > bottom()) { doc.addPage(); masthead(false); }
        doc.text(`• ${n}`, L, doc.y, { width: W });
      }
    }

    // Footers once the page count is known.
    const range = doc.bufferedPageRange();
    const stamp = new Date().toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      const y = doc.page.height - doc.page.margins.bottom + 16;
      doc.font('Helvetica').fontSize(7).fillColor('#555');
      doc.text(t.classification ?? 'CONFIDENTIAL — Mari Energies internal use', L, y, { width: W / 2, lineBreak: false });
      doc.text(`Generated ${stamp} · Page ${i - range.start + 1} of ${range.count}`, L + W / 2, y, { width: W / 2, align: 'right', lineBreak: false });
    }
    doc.end();
  });
}
